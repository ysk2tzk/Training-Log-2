-- Run this once in the Supabase SQL editor before deploying the exercise manager.
-- The table intentionally starts empty so only manually curated exercises appear.
create table if not exists public.training_exercise (
  id bigint generated by default as identity primary key,
  name text not null unique,
  weight_enabled boolean not null default true,
  gear_enabled boolean not null default false,
  reps_placeholder text not null default '回',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint training_exercise_name_not_blank check (length(trim(name)) > 0),
  constraint training_exercise_placeholder_not_blank check (length(trim(reps_placeholder)) > 0)
);

create index if not exists training_exercise_active_name_idx
  on public.training_exercise (active, name);
